#!/usr/bin/env python3
"""Regenerate every figure of papers/paper_draft.md and build its PDF in one run.

Run from the repo root with .venv/bin/python tools/export_paper.py.

The figure PNGs are build output (gitignored); what is tracked is the code that
draws them, and this script calls all of it:

  Figure 1  figures/control_subdivision.py           synthetic geometry
  Figure 2  figures/koz_linearization.py             synthetic geometry
  Figure 3  figures/scp_pipeline.py                  flowchart
  Figure 4  tools/build_representative_trajectories  the five scenarios, solved fresh
  Figure 5  tools/build_monte_carlo_figure.py        doc/results/monte_carlo_subdivision
  Figure 6  tools/build_normal_term_figure.py        doc/results/normal_term_ablation

Figure 4 is the only one that runs the solver. Each solve must reproduce its
committed row in doc/results/paper_tables.csv (Table 2), or the export stops: the
figure would otherwise show trajectories the table does not describe.

Output: papers/paper_draft.pdf. TeX and build logs go to --work-dir.
Requires Pandoc, XeLaTeX, and the fonts named in tools/export_paper_header.tex.
"""
import argparse
import csv
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parent.parent
DRAFT = ROOT / 'papers/paper_draft.md'
PDF = ROOT / 'papers/paper_draft.pdf'
LUA = ROOT / 'tools/export_paper.lua'
HEADER = ROOT / 'tools/export_paper_header.tex'

FIGURE_SCRIPTS = ['figures/control_subdivision.py', 'figures/koz_linearization.py',
                  'figures/scp_pipeline.py', 'tools/build_monte_carlo_figure.py']


def figure4():
    """Solve the five Table 2 scenarios, check them against the committed rows, draw."""
    import numpy as np
    from tools import build_representative_trajectories as f4

    with open(ROOT / 'doc/results/paper_tables.csv', newline='') as fh:
        rows = {r['scenario']: r for r in csv.DictReader(fh)
                if int(r['degree']) == f4.T2_DEGREE and int(r['n_seg']) == f4.T2_NSEG}
    taus = np.linspace(0.0, 1.0, f4.SAMPLES)
    solved = []
    for (name, _), color in zip(f4.T2_SCENARIOS, f4.COLORS):
        sc = f4.H.make_scenario(name, N=f4.T2_DEGREE)
        P, info = f4.H.run_rust(sc, n_seg=f4.T2_NSEG,
                                scp_trust_radius=f4.PAPER_R0.get(name, sc['r0']))
        margin = float(info['min_radius']) - sc['r_e']
        row = rows[name]
        got = (round(margin, 2), f"{float(info['cost']):.6e}", int(info['iterations']))
        want = (round(float(row['margin_km']), 2), f"{float(row['objective']):.6e}",
                int(row['iters']))
        if got != want:
            sys.exit(f'{name}: solver gives (clearance km, J, iterations) = {got}, '
                     f'doc/results/paper_tables.csv has {want}')
        pts = f4.H.positions(P, taus)
        k = int(np.argmin(np.linalg.norm(pts, axis=1)))
        solved.append((f4.LABEL[name], color, sc, pts, k, margin, 0 < k < len(taus) - 1, info))
    f4.main(solved=solved)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--work-dir', type=Path,
                        default=Path(tempfile.gettempdir()) / 'bezier-paper-pdf')
    args = parser.parse_args()
    work = args.work_dir.resolve()
    work.mkdir(parents=True, exist_ok=True)
    os.environ.setdefault('MPLCONFIGDIR', str(work / 'matplotlib'))
    os.environ['MPLBACKEND'] = 'Agg'
    sys.path.insert(0, str(ROOT))

    # 1. Figures. Every PNG the draft uses must be rewritten by this run.
    start = time.time()
    for script in FIGURE_SCRIPTS:
        subprocess.run([sys.executable, str(ROOT / script), '--save'], cwd=ROOT, check=True)
    subprocess.run([sys.executable, str(ROOT / 'tools/build_normal_term_figure.py')],
                   cwd=ROOT, check=True)
    figure4()
    images = re.findall(r'!\[[^\]]*\]\(\.\./(figures/[^)]+)\)', DRAFT.read_text())
    assert len(images) == 6, images
    for rel in images:
        path = ROOT / rel
        if not path.is_file() or path.stat().st_mtime < start:
            sys.exit(f'{rel} was not regenerated by this run')

    # 2. PDF, built from the draft itself; image paths resolve from papers/.
    tex = work / 'paper.tex'
    subprocess.run(['pandoc', str(DRAFT), '--standalone', '--from=markdown-implicit_figures',
                    '--to=latex', '--lua-filter=' + str(LUA),
                    '--include-in-header=' + str(HEADER),
                    '-V', 'mainfont=Helvetica Neue', '-V', 'mathfont=latinmodern-math.otf',
                    '-V', 'geometry:margin=0.85in', '-V', 'fontsize=10pt',
                    '-V', 'linestretch=1.1', '-V', 'colorlinks=true', '-o', str(tex)],
                   cwd=DRAFT.parent, check=True)
    for pass_no in (1, 2):
        with (work / f'build-{pass_no}.stdout').open('w') as log:
            subprocess.run(['xelatex', '-interaction=nonstopmode', '-halt-on-error',
                            '-output-directory=' + str(work), str(tex)],
                           cwd=DRAFT.parent, stdout=log, stderr=subprocess.STDOUT, check=True)

    # 3. The log must show no missing glyph and no unresolved reference.
    log = (work / 'paper.log').read_text(errors='replace')
    problems = [line for line in log.splitlines()
                if 'Missing character' in line or re.search(r'undefined (reference|on input)', line)]
    if problems:
        sys.exit('XeLaTeX log:\n' + '\n'.join(problems[:20]))
    overfull = len(re.findall(r'^Overfull \\hbox', log, re.M))

    PDF.write_bytes((work / 'paper.pdf').read_bytes())
    print(f'Wrote {PDF.relative_to(ROOT)}')
    print(f'Overfull lines: {overfull}. TeX and logs: {work}')


if __name__ == '__main__':
    main()
